#!/usr/bin/env node
/** Concatenate css/* into style.css + css/screens.css (no @import waterfall). */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const assetV = (() => {
  const sw = fs.readFileSync(path.join(root, "sw.js"), "utf8");
  const m = sw.match(/ASSET_V\s*=\s*"(\d+)"/);
  return m ? m[1] : "0";
})();

const CORE = [
  "tokens.css",
  "base.css",
  "layout.css",
  "components.css",
  "setup.css",
  "timer.css",
  "mobile.css"
];

const SCREENS = [
  "report.css",
  "history.css",
  "insights.css",
  "notes.css",
  "todos.css",
  "customize.css",
  "settings.css"
];

function bundle(files, outRel, banner) {
  const parts = [
    `/* ${banner} — generated by scripts/bundle-css.cjs (v=${assetV}). Edit css/* then re-run. */`,
    ""
  ];
  for (const name of files) {
    const src = fs.readFileSync(path.join(root, "css", name), "utf8").trim();
    parts.push(`/* --- css/${name} --- */`, src, "");
  }
  const out = path.join(root, outRel);
  fs.writeFileSync(out, `${parts.join("\n").trim()}\n`);
  return out;
}

const coreOut = bundle(CORE, "style.css", "Locked-In core CSS");
const screensOut = bundle(SCREENS, "css/screens.css", "Locked-In screen CSS");
console.log(`bundled ${path.relative(root, coreOut)} + ${path.relative(root, screensOut)} (v${assetV})`);
